const ALL = { ...WORDS, ...PHRASES, ...BATCH2, ...BATCH3, ...BATCH4, ...BATCH5, ...BATCH6, ...BATCH7, ...BATCH8, ...BATCH9, ...BATCH10, ...BATCH11, ...BATCH12, ...BATCH13, ...BATCH14 };
const KEYS = Object.keys(ALL).sort((a, b) => b.length - a.length);

function translateText(t) {
  let s = t;
  let out = '';
  let i = 0;
  while (i < s.length) {
    let matched = false;
    for (const k of KEYS) {
      if (s.startsWith(k, i)) {
        out += ALL[k];
        i += k.length;
        matched = true;
        break;
      }
    }
    if (!matched) {
      out += s[i];
      i++;
    }
  }
  // Tidy spaces around ASCII, collapse doubles
  out = out.replace(/\s+/g, ' ').trim();
  out = out.replace(/\s+([,.;:!?）)】])/g, '$1').replace(/([（(【])\s+/g, '$1');
  out = out.replace(/\(\s+/g, '(').replace(/\s+\)/g, ')');
  out = out.replace(/ ：/g, ':').replace(/：/g, ':');
  return out;
}

function main() {
  const files = process.argv.slice(2);
  let totalLines = 0, totalUnknown = 0;
  const unknownTerms = new Map();
  const recordUnknown = (en) => {
    const segs = en.match(/[\u4e00-\u9fff]+/g) || [];
    for (const sg of segs) unknownTerms.set(sg, (unknownTerms.get(sg) || 0) + 1);
    totalUnknown++;
  };
  for (const file of files) {
    if (!fs.existsSync(file)) continue;
    const src = fs.readFileSync(file, 'utf8');
    const lines = src.split('\n');
    let changed = false;
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      if (!HAN_RE.test(line)) continue;
      const trimmed = line.trim();
      const isLeading = trimmed.startsWith('//') || trimmed.startsWith('/*') || trimmed.startsWith('*');
      if (isLeading) {
        const indent = line.match(/^\s*/)[0];
        const m = trimmed.match(/^(\/\/+|\/\*\*?|\*+)\s*/);
        const marker = m ? m[1] : '';
        let core = trimmed.slice(marker.length);
        const tailClose = /\*\/\s*$/.test(core) ? ' */' : '';
        if (tailClose) core = core.replace(/\*\/\s*$/, '');
        if (!HAN_RE.test(core)) continue;
        const en = translateText(core.trim());
        if (HAN_RE.test(en)) { recordUnknown(en); continue; }
        lines[i] = indent + marker + (en ? ' ' + en : '') + tailClose;
        changed = true;
        totalLines++;
      } else {
        // Trailing comment after code: translate the //... segment only
        const idx = line.indexOf('//');
        if (idx === -1) continue;
        const before = line.slice(0, idx);
        if (before.includes('"') || before.includes("'") || before.includes('`')) continue; // risky: inside a string literal
        const seg = line.slice(idx);
        if (!HAN_RE.test(seg)) continue;
        const sm = seg.match(/^\/+/); // marker = one or more slashes, no space captured
        const smarker = sm ? sm[0] : '//';
        const score = seg.slice(smarker.length);
        const en = translateText(score.trim());
        if (HAN_RE.test(en)) { recordUnknown(en); continue; }
        lines[i] = before + smarker + (en ? ' ' + en : '');
        changed = true;
        totalLines++;
      }
    }
    if (changed) fs.writeFileSync(file, lines.join('\n'));
  }
  console.log(`translated=${totalLines} partial-skipped=${totalUnknown}`);
  const arr = [...unknownTerms.entries()].sort((a, b) => b[1] - a[1]).slice(0, 60);
  for (const [k, v] of arr) console.log('  UNKNOWN', v, k);
  fs.writeFileSync(path.join(HERE, 'comment-unknown.json'), JSON.stringify([...unknownTerms.entries()], null, 1));
}

main();
